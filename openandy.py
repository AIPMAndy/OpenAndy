#!/usr/bin/env python3
"""OpenAndy CLI — zero-dependency reader for an open, machine-readable knowledge base.

Commands:
    list             list all indexed entries
    ask <words...>   search entries by keyword (OR semantics, weighted)
    show <id>        print one entry in full
    check            validate index, links, sources, privacy and generated file
    build            regenerate llms-full.txt from Markdown (single source of truth)

No third-party packages, no network access, no model calls.
Python 3.9+.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from urllib.parse import unquote

DEFAULT_ROOT = Path(__file__).resolve().parent
INDEX_REL = "data/index.json"
LLMS_FULL = "llms-full.txt"

LINK_RE = re.compile(r"\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")
SENSITIVE_PATTERNS = [
    (re.compile(r"(?<!\d)1[3-9]\d{9}(?!\d)"), "mainland-China mobile number"),
    (re.compile(r"(?<!\d)\d{17}[\dXx](?!\d)"), "18-digit ID number"),
    (re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}"), "email address"),
    (re.compile(r"-----BEGIN (?:RSA |OPENSSH |EC |)PRIVATE KEY-----"), "private key"),
]

EXTRA_DOCS = ("AGENTS.md", "CONTRIBUTING.md", "README_EN.md")
SCAN_SUFFIXES = (".md", ".txt", ".json", ".html")


# --------------------------------------------------------------------------- io

def load_index(root: Path) -> dict:
    path = root / INDEX_REL
    with path.open(encoding="utf-8") as f:
        return json.load(f)


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def collect_docs(root: Path, index: dict) -> list[tuple[str, Path]]:
    """Markdown is the single source of truth. Order is deterministic."""
    docs: list[tuple[str, Path]] = []
    readme = root / "README.md"
    if readme.exists():
        docs.append(("README.md", readme))
    for entry in index["entries"]:
        p = root / entry["path"]
        if not p.is_file():
            raise FileNotFoundError(f"indexed file missing: {entry['path']}")
        docs.append((entry["path"], p))
    for name in EXTRA_DOCS:
        p = root / name
        if p.is_file():
            docs.append((name, p))
    return docs


def build_text(root: Path, index: dict) -> str:
    """Render llms-full.txt. Pure function of the Markdown + index (idempotent)."""
    out = [
        "# OpenAndy — llms-full.txt",
        "",
        "> Generated by `python3 openandy.py build`. Do not edit by hand.",
        "> Markdown files are the single source of truth; this file is a build artifact.",
        f"> Version {index.get('version', 'unknown')} · updated {index.get('updated', 'unknown')}",
        "",
        "## Read this first",
        "",
        "This repository records ONE person's public self-account (2026-11-07) and the",
        "working rules he uses. It is not verified history, not a success formula, and not",
        "an AI clone of the author. Fact grades must be preserved:",
        "",
        "- `[公开自述]` public self-account, unaudited",
        "- `[工作原则]` the author's working rules",
        "- `[本仓库整理]` derived checklists, not facts",
        "- `[存疑]` conflicting or insufficient evidence",
        "",
        "Rules for AI readers: never reconcile conflicting dates, never turn correlation",
        "into causation, never produce income predictions or medical/investment advice,",
        "never invent names, employers, contract values or private contact details.",
        "See AGENTS.md and SOURCES.md in this file for the full rules.",
        "",
        "## Sources",
        "",
    ]
    for sid, src in index.get("sources", {}).items():
        url = src.get("url") or "no public URL"
        out.append(f"- {sid}: {src.get('title', '')} ({src.get('date', '')}) — {url}")
    out.append("")
    out.append("## Documents")
    out.append("")
    for rel, path in collect_docs(root, index):
        out.append(f"- {rel}")
    out.append("")
    for rel, path in collect_docs(root, index):
        out.extend(["---", "", f"## FILE: {rel}", "", read_text(path).rstrip(), ""])
    return "\n".join(out).rstrip() + "\n"


# -------------------------------------------------------------------- commands

def cmd_list(root: Path, index: dict, args) -> int:
    print(f"OpenAndy {index.get('version', '?')} · {len(index['entries'])} entries · {root}")
    print("-" * 72)
    for e in index["entries"]:
        print(f"{e['id']:<16} {e['title']}")
        print(f"{'':<16} {e['path']}  [{', '.join(e['sources'])}]")
    return 0


def search_entries(root: Path, index: dict, terms: list[str]) -> list[tuple[int, dict, list[str]]]:
    """Weighted OR search: title 3, tags 2, summary 1, body 1 per term."""
    results = []
    for e in index["entries"]:
        path = root / e["path"]
        body = read_text(path).lower() if path.is_file() else ""
        title, summary = e["title"].lower(), e["summary"].lower()
        tags = [t.lower() for t in e.get("tags", [])]
        score, hits = 0, []
        for raw in terms:
            q = raw.strip().lower()
            if not q:
                continue
            s = 0
            if q in title:
                s += 3
            if any(q in t for t in tags):
                s += 2
            if q in summary:
                s += 1
            if q in body:
                s += 1
            if s:
                score += s
                hits.append(raw)
        if score:
            results.append((score, e, hits))
    results.sort(key=lambda r: (-r[0], r[1]["id"]))
    return results


def cmd_ask(root: Path, index: dict, args) -> int:
    results = search_entries(root, index, args.words)
    if not results:
        print("没有匹配的条目。本仓库只覆盖这个仓库里记录的内容，不推断。")
        print("试试：python3 openandy.py list")
        return 0
    limit = args.limit
    print(f"检索：{' / '.join(args.words)} · 命中 {len(results)} 条 · 显示前 {min(limit, len(results))} 条\n")
    for score, e, hits in results[:limit]:
        print(f"[{score:>2} 分] {e['id']} — {e['title']}   (命中 {', '.join(hits)})")
        print(f"       {e['summary']}")
        print(f"       文件：{e['path']} · 来源：{', '.join(e['sources'])}")
        print()
    print("事实分级与口径见 SOURCES.md；引用前请核对原文。")
    return 0


def cmd_show(root: Path, index: dict, args) -> int:
    for e in index["entries"]:
        if e["id"] == args.id:
            path = root / e["path"]
            print(f"# {e['title']}\n\n> 文件：{e['path']} · 来源：{', '.join(e['sources'])}\n")
            print(read_text(path))
            return 0
    print(f"未知 id：{args.id}。运行 `python3 openandy.py list` 查看全部条目。", file=sys.stderr)
    return 2


def cmd_build(root: Path, index: dict, args) -> int:
    text = build_text(root, index)
    target = root / LLMS_FULL
    old = read_text(target) if target.is_file() else None
    if old == text:
        print(f"{LLMS_FULL} 已是最新（{len(text.encode('utf-8'))} 字节，未改动）")
        return 0
    target.write_text(text, encoding="utf-8")
    print(f"已生成 {LLMS_FULL}（{len(text.encode('utf-8'))} 字节，{len(index['entries'])} 个条目）")
    return 0


def check_links(root: Path, index: dict, errors: list[str]) -> int:
    """Every relative Markdown link must resolve. This catches index/content drift."""
    checked = 0
    docs = collect_docs(root, index)
    for rel, path in docs:
        for target in LINK_RE.findall(read_text(path)):
            t = unquote(target.strip())
            if not t or t.startswith(("http://", "https://", "mailto:", "#")):
                continue
            t = t.split("#", 1)[0]
            if not t:
                continue
            resolved = (path.parent / t).resolve()
            checked += 1
            if not resolved.exists():
                errors.append(f"断链：{rel} -> {target}")
    return checked


def check_privacy(root: Path, errors: list[str]) -> int:
    scanned = 0
    paths = [p for p in root.rglob("*") if p.is_file() and p.suffix.lower() in SCAN_SUFFIXES]
    for p in sorted(paths):
        if ".git" in p.parts or "__pycache__" in p.parts or p.name.startswith("."):
            continue
        text = read_text(p)
        scanned += 1
        for pattern, label in SENSITIVE_PATTERNS:
            m = pattern.search(text)
            if m:
                errors.append(f"疑似隐私信息（{label}）：{p.relative_to(root)} -> {m.group(0)[:24]}")
    return scanned


def cmd_check(root: Path, index: dict, args) -> int:
    errors: list[str] = []
    print("OpenAndy check\n" + "-" * 60)

    # 1. index structure
    if not index.get("version") or not index.get("updated"):
        errors.append("index 缺少 version / updated")
    sources = index.get("sources", {})
    entries = index.get("entries", [])
    if not sources:
        errors.append("index 缺少 sources")
    if not entries:
        errors.append("index 缺少 entries")
    print(f"[{'PASS' if sources and entries else 'FAIL'}] 索引结构：{len(sources)} 个来源 / {len(entries)} 个条目")

    # 2. entries integrity
    entry_errors: list[str] = []
    seen = set()
    for e in entries:
        for key in ("id", "title", "path", "tags", "summary", "sources"):
            if key not in e:
                entry_errors.append(f"条目缺少字段 {key}：{e.get('id', '?')}")
        eid = e.get("id", "?")
        if eid in seen:
            entry_errors.append(f"重复 id：{eid}")
        seen.add(eid)
        p = root / e.get("path", "")
        if not p.is_file():
            entry_errors.append(f"条目文件不存在：{e.get('path')}")
        if not e.get("tags"):
            entry_errors.append(f"条目缺少标签：{eid}")
        for sid in e.get("sources", []):
            if sid not in sources:
                entry_errors.append(f"条目 {eid} 引用了未登记来源：{sid}")
    errors.extend(entry_errors)
    print(f"[{'PASS' if not entry_errors else 'FAIL'}] 条目完整性：id 唯一 / 路径存在 / 来源已登记")

    # 3. source of truth: index must hold metadata only, never body text
    index_raw = read_text(root / INDEX_REL)
    duplication_errors: list[str] = []
    for e in entries:
        p = root / e.get("path", "")
        if not p.is_file():
            continue
        body = read_text(p)
        if e.get("summary") and e["summary"] in body:
            duplication_errors.append(f"索引摘要与正文重复：{e['id']}")
        longest = max((line.strip() for line in body.splitlines() if len(line.strip()) > 60), default="")
        if longest and longest in index_raw:
            duplication_errors.append(f"索引疑似复制正文段落：{e['id']}")
    errors.extend(duplication_errors)
    print(f"[{'PASS' if not duplication_errors else 'FAIL'}] 单一真源：索引未复制正文")

    # 4. relative links
    link_errors: list[str] = []
    try:
        n_links = check_links(root, index, link_errors)
    except FileNotFoundError as exc:
        n_links = 0
        link_errors.append(str(exc))
    errors.extend(link_errors)
    print(f"[{'PASS' if not link_errors else 'FAIL'}] 相对链接：检查 {n_links} 条，断链 {len(link_errors)} 条")

    # 5. privacy scan
    privacy_errors: list[str] = []
    n_files = check_privacy(root, privacy_errors)
    errors.extend(privacy_errors)
    print(f"[{'PASS' if not privacy_errors else 'FAIL'}] 隐私扫描：检查 {n_files} 个文件，命中 {len(privacy_errors)} 处")

    # 6. generated file in sync
    target = root / LLMS_FULL
    if not target.is_file():
        errors.append(f"{LLMS_FULL} 不存在，请先运行 `python3 openandy.py build`")
        sync = False
    else:
        try:
            sync = read_text(target) == build_text(root, index)
        except FileNotFoundError as exc:
            sync = False
            errors.append(str(exc))
        if not sync:
            errors.append(f"{LLMS_FULL} 与 Markdown 不同步，请重新 build")
    print(f"[{'PASS' if sync else 'FAIL'}] 构建产物：{LLMS_FULL} 与正文一致")

    # 7. rules doc present
    for required in ("SOURCES.md", "AGENTS.md", "llms.txt"):
        if not (root / required).is_file():
            errors.append(f"缺少必需文件：{required}")
    print(f"[{'PASS' if all((root / r).is_file() for r in ('SOURCES.md', 'AGENTS.md', 'llms.txt')) else 'FAIL'}] 必需文件：SOURCES.md / AGENTS.md / llms.txt")

    print("-" * 60)
    if errors:
        for err in errors:
            print(f"  ✗ {err}")
        print(f"\nFAILED：{len(errors)} 个问题。")
        return 1
    print("全部通过。")
    return 0


# ------------------------------------------------------------------------ main

def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="OpenAndy — 开源个人知识库的零依赖阅读器",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument("--root", type=Path, default=DEFAULT_ROOT, help="仓库根目录（默认：脚本所在目录）")
    sub = parser.add_subparsers(dest="command", required=True)

    sub.add_parser("list", help="列出全部条目")
    p_ask = sub.add_parser("ask", help="按关键词检索（多个词为“或”关系）")
    p_ask.add_argument("words", nargs="+", help="一个或多个关键词")
    p_ask.add_argument("--limit", type=int, default=5, help="显示条数（默认 5）")
    p_show = sub.add_parser("show", help="输出某条目全文")
    p_show.add_argument("id", help="条目 id，见 list")
    sub.add_parser("check", help="校验索引、链接、来源、隐私与构建产物")
    sub.add_parser("build", help="从 Markdown 重新生成 llms-full.txt")

    args = parser.parse_args(argv)
    root: Path = args.root.resolve()
    try:
        index = load_index(root)
    except (OSError, json.JSONDecodeError) as exc:
        print(f"无法读取 {root / INDEX_REL}：{exc}", file=sys.stderr)
        return 2

    handlers = {
        "list": cmd_list,
        "ask": cmd_ask,
        "show": cmd_show,
        "check": cmd_check,
        "build": cmd_build,
    }
    try:
        return handlers[args.command](root, index, args)
    except (FileNotFoundError, KeyError, OSError) as exc:
        print(f"执行 {args.command} 失败：{exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
